import { ShieldCheck, ScrollText, X } from 'lucide-react'

export type LegalDocument = 'terms' | 'privacy'

type LegalDialogProps = {
  document: LegalDocument
  onChange: (document: LegalDocument) => void
  onClose: () => void
  supportEmail: string
}

export default function LegalDialog({ document, onChange, onClose, supportEmail }: LegalDialogProps) {
  return (
    <div className="modal-backdrop" role="presentation" onMouseDown={(event) => {
      if (event.target === event.currentTarget) onClose()
    }}>
      <section className="legal-modal" role="dialog" aria-modal="true" aria-labelledby="legal-title">
        <div className="modal-heading">
          <span className="modal-icon">{document === 'terms' ? <ScrollText size={18} /> : <ShieldCheck size={18} />}</span>
          <button className="modal-close" type="button" onClick={onClose} aria-label="Закрыть"><X size={18} /></button>
        </div>
        <div className="legal-tabs" role="tablist" aria-label="Документы">
          <button id="terms-tab" role="tab" aria-selected={document === 'terms'} className={document === 'terms' ? 'active' : ''} onClick={() => onChange('terms')}>Условия использования</button>
          <button id="privacy-tab" role="tab" aria-selected={document === 'privacy'} className={document === 'privacy' ? 'active' : ''} onClick={() => onChange('privacy')}>Конфиденциальность</button>
        </div>
        <div className="legal-content" role="tabpanel" aria-labelledby={`${document}-tab`}>
          {document === 'terms' ? (
            <>
              <h2 id="legal-title">Условия использования</h2>
              <p className="legal-updated">Последнее обновление: 17 октября 2026 года</p>
              <h3>1. О сервисе</h3>
              <p>FocusFlow — бесплатный инструмент для самостоятельного планирования задач и запуска фокус-таймера. Демо, создание списков и задач, а также Pomodoro-таймер не требуют оплаты или банковской карты.</p>
              <h3>2. Аккаунт и содержание планов</h3>
              <p>Аккаунт и синхронизация становятся доступны после подключения Supabase. Пользователь отвечает за сохранность доступа к своей почте и достоверность сведений, переданных при регистрации. Списки, названия задач, расписание и приоритеты создаёт сам пользователь.</p>
              <h3>3. Допустимое использование</h3>
              <p>Не используй сервис для хранения чужих паролей, медицинских сведений, финансовых секретов и иной информации, которую не следует передавать веб-приложению. Сервис не заменяет профессиональную медицинскую, юридическую или финансовую консультацию.</p>
              <h3>4. Доступность и ответственность</h3>
              <p>Демо работает в текущем браузере; аккаунты и синхронизация требуют настройки облачного проекта. Неподключённые функции явно обозначаются в приложении. Перед официальным коммерческим запуском владелец сервиса должен дополнить документ своими реквизитами и проверить его у юриста.</p>
              <h3>5. Связь с владельцем</h3>
              <p>{supportEmail ? <>Напиши на <a href={`mailto:${supportEmail}`}>{supportEmail}</a> по вопросам использования сервиса.</> : <>Настройка контактной почты описана в README репозитория проекта.</>}</p>
            </>
          ) : (
            <>
              <h2 id="legal-title">Политика конфиденциальности</h2>
              <p className="legal-updated">Последнее обновление: 17 октября 2026 года</p>
              <h3>1. Демо без регистрации</h3>
              <p>Без аккаунта задачи и собственные списки сохраняются только в локальном хранилище браузера на этом устройстве. В режиме демо FocusFlow не отправляет задачи на сервер. Очистка данных сайта в браузере удаляет локальный демо-план.</p>
              <h3>2. Учётная запись и синхронизация</h3>
              <p>Регистрация включается только после настройки владельцем проекта Supabase. При подключённом аккаунте Supabase Auth обрабатывает адрес электронной почты и учётные данные, а связанные с аккаунтом названия списков и задач, время, приоритет и статус сохраняются в таблицах Supabase. Пароль FocusFlow не сохраняет и не видит. Политики Row Level Security ограничивают доступ к строкам владельцем аккаунта.</p>
              <h3>3. Хранение и права пользователя</h3>
              <p>В деморежиме данные хранятся в вашем браузере. В режиме аккаунта данные обрабатываются в том проекте и регионе Supabase, который настроил владелец приложения; его регион необходимо проверить в настройках проекта. Чтобы запросить удаление данных аккаунта, свяжитесь с владельцем по настроенному адресу поддержки. Не публикуйте персональные данные и запросы на удаление в общедоступных GitHub Issues.</p>
              <h3>4. Браузер и сторонние запросы</h3>
              <p>Supabase хранит сессию входа в браузере для работы и обновления аккаунта. Внешние веб-шрифты DM Sans и Manrope загружаются с Google Fonts, если браузер может обратиться к Google; при этом Google может получить стандартные технические данные запроса. Таймер не сохраняет историю сессий. Показанная недельная диаграмма — демонстрационная и не записывает активность.</p>
              <h3>5. Получатели, продажа данных и выбор пользователя</h3>
              <p>Сервис не продаёт рекламным платформам адреса почты, содержимое задач или историю продуктивности. Supabase обрабатывает данные аккаунта только если включена регистрация; Google Fonts — технические данные при загрузке шрифтов. Пользователь может продолжать пользоваться демоверсией без создания аккаунта.</p>
              <h3>6. Контакт и важное примечание</h3>
              <p>{supportEmail ? <>По вопросам доступа к данным: <a href={`mailto:${supportEmail}`}>{supportEmail}</a>.</> : <>Настройка контактной почты описана в README репозитория проекта.</>} До публичного коммерческого запуска владелец сервиса должен указать свои юридические реквизиты, регион обработки данных и проверенные контактные данные, а затем провести юридическую проверку этой политики.</p>
            </>
          )}
        </div>
        <div className="legal-footer">Пользуйся FocusFlow осознанно и сохраняй только ту информацию, которой готов поделиться с выбранным облачным сервисом.</div>
      </section>
    </div>
  )
}
